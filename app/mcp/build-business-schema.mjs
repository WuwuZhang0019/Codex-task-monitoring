import { build } from 'esbuild';
import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { bundledLicenses } from './licenses.mjs';

export async function buildBusinessSchema() {
  const source = fileURLToPath(new URL('./business-schema-source.mjs', import.meta.url));
  const output = fileURLToPath(new URL('../server/business-schema.mjs', import.meta.url));
  const workingDirectory = fileURLToPath(new URL('../', import.meta.url));
  const schema = await readFile(new URL('./contracts/v1.json', import.meta.url));
  const fingerprint = createHash('sha256').update(schema).digest('hex');
  const result = await build({ absWorkingDir: workingDirectory, entryPoints: [source], outfile: output, bundle: true, platform: 'node', format: 'esm', target: 'node22',
    write: false, metafile: true, external: ['../server/validation.mjs'] });
  const { licenses } = await bundledLicenses(result.metafile, workingDirectory);
  const date = new Intl.DateTimeFormat('sv-SE', { timeZone: 'Asia/Shanghai' }).format(new Date());
  const header = `/*\n日期：${date}\nGenerated by mcp/build-business-schema.mjs. Source schema SHA256 ${fingerprint}\n${licenses.join('\n\n---\n\n')}\n*/\n`;
  await writeFile(output, `${header}export const contractFingerprint = ${JSON.stringify(fingerprint)};\n${result.outputFiles[0].text}`, 'utf8');
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) await buildBusinessSchema();
